import re
from CausalDiagnosis.experiments.table_definitions.experiment_tables import MCP
from . import table_cells, markdown_page


PREAMBLE = (r"\documentclass[10pt]{article}", r"\usepackage[paperwidth=10in,paperheight=14in,margin=0.3in]{geometry}",
            r"\usepackage{booktabs,times,caption,float,array}", r"\captionsetup{font=small,labelformat=empty,skip=4pt}", r"\pagestyle{empty}",
            # a cell of the main result tables, the mean and under it in smaller type its standard error, as the paper prints them
            r"\newcommand{\st}[2]{\begin{tabular}[c]{@{}c@{}}#1\\[-2.5pt]{\scriptsize #2}\end{tabular}}",
            r"\begin{document}")


# ----- the LaTeX form -----
def tex_signs(text):
    """The signs of the tables in LaTeX, alone for a header line that is LaTeX already."""
    text = text.replace(table_cells.PLUS_MINUS, r"$\pm$").replace(table_cells.DELTA, r"$\Delta$").replace(table_cells.DAGGER, r"$^\dagger$").replace(table_cells.KAPPA, r"$\kappa$").replace("<", r"$<$")
    text = text.replace(table_cells.SHORT, r"$^\ddagger$")
    text = text.replace(table_cells.DASH, "$-$")
    text = re.sub(r"\^(\d+)", r"$^{\1}$", text)  # the k of pass^k, a superscript
    return re.sub(r"\bHolm p\b", r"Holm $p$", text)  # the paper sets the p of a Holm column in math


def tex_text(text):
    """A text of the tables in LaTeX: the characters a model name or a header holds, and the signs of the tables."""
    for character in "_%&#$":
        text = text.replace(character, rf"\{character}")
    return tex_signs(text)


def tex_lines(table):
    out = []
    for position, group in enumerate(table.groups):
        if position:
            out.append(r"\addlinespace[3pt]" if table.spaced else r"\midrule")
        for index, (labels, cells) in enumerate(group):
            names = [tex_text(label) for label in labels]
            if table.first_only and index:
                names[0] = ""
            elif table.stacked_first and names[0].endswith(f" + {MCP}"):
                names[0] = table_cells.stacked(names[0].removesuffix(f" + {MCP}"), f"+ {MCP}", align="l", vertical=table.stacked_first)
            if table.indented and names[0].startswith("+ "):
                names[0] = r"\quad " + names[0]
            if isinstance(labels[-1], table_cells.Marked) and labels[-1].short:
                names[-1] += tex_signs(table_cells.SHORT)
            out.append(" & ".join([*names, *(tex_text(cell.short) for cell in cells)]) + r" \\")
    return out


def tex_tabular(table):
    header = [tex_signs(line) for line in table.tex_header] if table.tex_header else [" & ".join(map(tex_text, table.header)) + r" \\"]
    caption = tex_text(table.caption) + (" " + table.counting[1] if table.counting else "")
    return [rf"\caption{{\textbf{{{tex_text(table.title)}.}} {caption}}}", rf"\label{{tab:{table.label}}}", r"\setlength{\tabcolsep}{3pt}",
            rf"\begin{{tabular}}{{{table.tex_format}}}", r"\toprule", *header, r"\midrule", *tex_lines(table), r"\bottomrule", r"\end{tabular}"]


def tex_float(table):
    """One table in a float that stays where the sheet puts it."""
    return [r"\begin{table}[H]\centering\footnotesize", *tex_tabular(table), r"\end{table}"]


def latex(built, tables):
    """main_tables.tex in the layout of the paper's result tables, the tables of a model on pages of their own."""
    out = ["% generated by CausalDiagnosis/evaluation/result_tables/paper_tables.py from the aggregate tables, so edit that file and not this one", *PREAMBLE]
    if not (tables["AGENTS"] or tables["POLICIES"] or tables["OFFLINE"]):
        out += [rf"\begin{{center}}\small\textbf{{{markdown_page.SENTENCE_NO_RUN}}}\end{{center}}", r"\vspace{-8pt}"]
    for position, (sheet, sections) in enumerate(built):
        if position:
            out.append(r"\clearpage")
        if sheet.model:
            out += [rf"\begin{{center}}\small\textbf{{{tex_text(sheet.model)}}}\end{{center}}", r"\vspace{-8pt}"]
        for title, section in zip(markdown_page.HEADINGS, sections):
            out += [rf"\begin{{center}}\footnotesize\textit{{{title}}}\end{{center}}", r"\vspace{-10pt}"]
            for table in section:
                out += [*tex_float(table), r"\vspace{-8pt}"]
    return "\n".join([*out, r"\end{document}"]) + "\n"
