import argparse
import sys
from pathlib import Path
from CausalDiagnosis.experiments.run_verification import run_ledger as ledger
from CausalDiagnosis.experiments.episode_runners.run_folder_layout import refuse_page_output
from . import formatting, episode_files, part_plain_words, part_start, part_verdict, part_steps, part_hidden


# the sentence of the page on its readers: it shows the hidden state of a finished run whatever its options
FOR_PEOPLE = "The page shows the hidden state of a finished run, so it is for people and is never handed to an agent."


# ----- the page -----
def files_read(ep):
    """The table of the files the page may read, every file of the episode folder with run.json and scores.csv of its run
    folder, each with its SHA-256 as the page was written, so that the review pack (CausalDiagnosis/episode_viewer/run_review_pack.py)
    matches the page with the run's ledger. Names that start with a dot, such as the .DS_Store of a Mac, and the files that no
    ledger records (ledger.ignored) are left out."""
    run = ep.folder.parent
    files = [p for p in sorted(ep.folder.rglob("*"))
             if p.is_file() and not p.name.startswith(".") and not ledger.ignored(p.relative_to(ep.folder))]
    files += [p for p in (run / "run.json", run / "scores.csv") if p.is_file()]
    rows = [[f"`{p.relative_to(run).as_posix()}`", ledger.sha256_of(p)] for p in files]
    return ["The page reads the files below, named from the run folder, with the SHA-256 of each when the page was written.", "",
            *formatting.table(["File", "SHA-256"], rows), ""]


def render(folder, note=None):
    ep = episode_files.Episode(folder)
    lines = [f"# Walkthrough of seed {formatting.num(ep.state.get('seed'))}, agent {ep.label()}", ""]
    if note:
        lines += [note, ""]
    lines += [f"Generated by `CausalDiagnosis/episode_viewer/walkthrough.py` from the episode folder `{ep.folder.parent.name}/{ep.folder.name}`. "
              "Parts 1, 2 and 5 show only what the agent could know, from its public files. Parts 3 and 4 open the hidden files of the "
              f"episode. {FOR_PEOPLE}", ""]
    lines += files_read(ep)
    for part in (part_start.part_start, part_steps.part_steps, part_hidden.part_hidden, part_verdict.part_verdict, part_plain_words.part_plain):
        lines += part(ep)
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write the walkthrough of one episode folder as Markdown.")
    ap.add_argument("episode", help="an episode folder of a run, such as <run folder>/seed000015")
    ap.add_argument("--out", help="the Markdown file to write, standard output when absent")
    ap.add_argument("--note", help="a paragraph under the title, such as the design version the run used")
    args = ap.parse_args(argv)
    if args.out:
        refuse_page_output(args.out, args.episode)
    text = render(args.episode, args.note)
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
